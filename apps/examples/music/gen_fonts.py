#!/usr/bin/env python3
"""Generate the Music app's icon fonts: the Material Icons a player needs that
the OS icon font leaves out (shuffle, repeat, queue, playlist, album, artist).
Uses the pinned Material Icons and the converter settings of
tools/assets/fonts.py.

    python3 apps/examples/music/gen_fonts.py      # needs Node (npx)

Writes music_icons_48.c (24 dp) and music_icons_80.c (40 dp) and
music_icons.h next to this script.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "assets"))
import fonts  # noqa: E402

ICONS = ["shuffle", "repeat", "repeat_one", "queue_music", "playlist_add", "album", "person", "queue_play_next",
         "playlist_play", "library_music"]
FONTS = [("music_icons_48", 48), ("music_icons_80", 80)]


def main():
    fonts.fetch(offline=False)
    cps = fonts.load_codepoints()
    missing = [n for n in ICONS if n not in cps]
    if missing:
        raise SystemExit("not in Material Icons: " + ", ".join(missing))
    ranges = ",".join("0x%X" % cps[n] for n in ICONS)
    for name, size in FONTS:
        tmp = os.path.join(fonts.CACHE, name + ".c")
        fonts.run_conv("MaterialIcons-Regular.ttf", size, ranges, name, tmp)
        with open(tmp, encoding="utf-8") as f:
            text = f.read()
        os.remove(tmp)
        opts = "%s --font MaterialIcons-Regular.ttf -r %s --size %d --bpp 4 --no-compress --no-prefilter --format lvgl" % (
            fonts.LV_FONT_CONV, ranges, size)
        text = fonts.patch(text, name, opts, None, None)
        text = text.replace("Generated by tools/assets/fonts.py", "Generated by apps/examples/music/gen_fonts.py")
        out = os.path.join(HERE, name + ".c")
        fonts.write(out, text)
        print("%s: about %d bytes" % (out, fonts.bitmap_bytes(out)))
    lines = ["/* Generated by apps/examples/music/gen_fonts.py. Do not edit. */",
             "#pragma once", '#include "lvgl.h"', "",
             "LV_FONT_DECLARE(music_icons_48)   /* 24 dp */",
             "LV_FONT_DECLARE(music_icons_80)   /* 40 dp */", ""]
    for n in ICONS:
        lines.append('#define MI_%s "%s"' % (n.upper(), fonts.utf8_escape(cps[n])))
    fonts.write(os.path.join(HERE, "music_icons.h"), "\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
