#!/usr/bin/env python3
"""Generate the Calculator's own fonts: Roboto with the maths symbols the OS
fonts leave out (minus, root, pi, infinity, superscripts). Uses the pinned
Roboto and the converter settings of tools/assets/fonts.py.

    python3 apps/examples/calculator/gen_fonts.py      # needs Node (npx)

Writes calc_font_40.c (keys, the previous line) and calc_font_80.c (the
main line) next to this script.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "assets"))
import fonts  # noqa: E402

# ASCII, then ± ² ³ · ¹ × ÷ ʸ ˣ π ⁰ ⁴-⁹ ⁻ − √ ∞.
RANGES = ("0x20-0x7E,0xB1,0xB2,0xB3,0xB7,0xB9,0xD7,0xF7,0x2B8,0x2E3,0x3C0,"
          "0x2070,0x2074-0x2079,0x207B,0x2212,0x221A,0x221E")
FONTS = [("calc_font_40", 40), ("calc_font_80", 80)]


def main():
    fonts.fetch(offline=False)
    for name, size in FONTS:
        tmp = os.path.join(fonts.CACHE, name + ".c")
        fonts.run_conv("Roboto-Regular.ttf", size, RANGES, name, tmp)
        with open(tmp, encoding="utf-8") as f:
            text = f.read()
        os.remove(tmp)
        opts = "%s --font Roboto-Regular.ttf -r %s --size %d --bpp 4 --no-compress --no-prefilter --format lvgl" % (
            fonts.LV_FONT_CONV, RANGES, size)
        text = fonts.patch(text, name, opts, ord("H"), ord("x"))
        text = text.replace("Generated by tools/assets/fonts.py", "Generated by apps/examples/calculator/gen_fonts.py")
        out = os.path.join(HERE, name + ".c")
        fonts.write(out, text)
        print("%s: about %d bytes" % (out, fonts.bitmap_bytes(out)))


if __name__ == "__main__":
    main()
