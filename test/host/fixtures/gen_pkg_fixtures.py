"""Generate test/host/fixtures/pkg_fixtures.h: raw DEFLATE streams and small
zips / .t5app packages as C byte arrays for test_pkg.c.

Deterministic (fixed seeds and timestamps), so re-running gives the same file.
Run: python3 test/host/fixtures/gen_pkg_fixtures.py
"""
import io
import os
import random
import struct
import zipfile
import zlib

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "pkg_fixtures.h")
DT = (2026, 1, 1, 0, 0, 0)

WORDS = ("tab5 esp32 deflate window huffman literal length distance block stored "
         "fixed dynamic manifest package install upgrade remove grant camera grove").split()


def words(seed, n):
    r = random.Random(seed)
    return " ".join(r.choice(WORDS) + ("\n" if r.random() < 0.1 else "") for _ in range(n)).encode()


def far_refs(seed, size):
    """Random blocks repeated at distances up to ~32 KB: exercises long back-references."""
    r = random.Random(seed)
    blocks = [bytes(r.getrandbits(8) for _ in range(96)) for _ in range(24)]
    out = bytearray()
    while len(out) < size:
        out += r.choice(blocks)
        out += words(r.random(), 20)
    return bytes(out[:size])


def raw_deflate(data, level=9, strategy=zlib.Z_DEFAULT_STRATEGY):
    c = zlib.compressobj(level, zlib.DEFLATED, -15, 9, strategy)
    return c.compress(data) + c.flush()


def make_zip(files, method=zipfile.ZIP_DEFLATED):
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as z:
        for name, data in files:
            zi = zipfile.ZipInfo(name, DT)
            zi.compress_type = method if not name.endswith("/") else zipfile.ZIP_STORED
            zi.external_attr = (0o40755 << 16) | 0x10 if name.endswith("/") else 0o644 << 16
            z.writestr(zi, data)
    return bytearray(buf.getvalue())


def manifest(version, entry="app.elf", extra="", api=1, icon=True):
    return (f'''# test app
id = "com.example.hello"
name = "Hello"
version = "{version}"
api = {api}
runtime = "native"
entry = "{entry}"
''' + ('icon = "icon.png"\n' if icon else "") + '''min_heap_mb = 1

[permissions]
ports = ["grove"]
net = true
''' + extra).encode()


def c_array(name, data):
    lines = [f"static const unsigned char {name}[] = {{"]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    lines.append(f"static const unsigned int {name}_len = {len(data)}u;")
    return "\n".join(lines)


def find_cdir(z, name):
    """Offset of the central directory record for name."""
    eocd = z.rfind(b"PK\x05\x06")
    n, size, off = struct.unpack_from("<HII", z, eocd + 10)
    p = off
    for _ in range(n):
        nlen, xlen, clen = struct.unpack_from("<HHH", z, p + 28)
        if z[p + 46:p + 46 + nlen] == name.encode():
            return p
        p += 46 + nlen + xlen + clen
    raise KeyError(name)


def main():
    out = ["/* Generated by gen_pkg_fixtures.py; do not edit. */", "#pragma once", ""]

    # --- raw deflate streams ---
    hello = b"Hello, Tab5! Hello, Tab5! Hello, Tab5! inflate me please."
    streams = {
        "fx_def_hello": (hello, raw_deflate(hello)),
        "fx_def_fixed": (words(1, 60), raw_deflate(words(1, 60), 9, zlib.Z_FIXED)),
        "fx_def_stored": (words(2, 400), raw_deflate(words(2, 400), 0)),
        "fx_def_medium": (words(3, 1200), raw_deflate(words(3, 1200))),
        "fx_def_big": (far_refs(4, 80000), raw_deflate(far_refs(4, 80000))),
        "fx_def_empty": (b"", raw_deflate(b"")),
    }
    for name, (plain, comp) in streams.items():
        assert zlib.decompress(comp, -15) == plain
        out.append(c_array(name, comp))
        out.append(f"#define {name.upper()}_SIZE {len(plain)}u")
        out.append(f"#define {name.upper()}_CRC 0x{zlib.crc32(plain):08x}u")
        out.append("")
    out.append(f'#define FX_DEF_HELLO_TEXT "{hello.decode()}"')
    out.append("")

    big_elf = far_refs(10, 50000)
    icon = bytes(random.Random(11).getrandbits(8) for _ in range(300))
    readme = words(12, 50)

    zips = {}
    # Plain zips for the reader.
    zips["fx_zip_stored"] = make_zip([("a.txt", b"alpha\n"), ("dir/", b""), ("dir/b.txt", readme)],
                                     zipfile.ZIP_STORED)
    zips["fx_zip_deflate"] = make_zip([("a.txt", b"alpha\n"), ("dir/", b""), ("dir/b.txt", readme),
                                       ("big.bin", big_elf)])

    bad = make_zip([("a.txt", b"alpha alpha alpha\n")], zipfile.ZIP_STORED)
    bad[bad.find(b"alpha alpha")] ^= 0x20          # payload changed, CRC not
    zips["fx_zip_badcrc"] = bad

    bad = make_zip([("text.txt", words(13, 3000))])
    lh = bad.find(b"PK\x03\x04")
    nlen, xlen = struct.unpack_from("<HH", bad, lh + 26)
    data = lh + 30 + nlen + xlen
    for i in range(0, 200, 7):
        bad[data + 100 + i] ^= 0x5a                    # corrupt the compressed stream
    zips["fx_zip_baddeflate"] = bad

    zips["fx_zip_traversal"] = make_zip([("ok.txt", b"ok"), ("../evil.txt", b"evil")])
    zips["fx_zip_absolute"] = make_zip([("/etc/evil.txt", b"evil")])
    zips["fx_zip_backslash"] = make_zip([("a\\..\\evil.txt", b"evil")])
    zips["fx_zip_longname"] = make_zip([("d/" * 70 + "x.txt", b"long")])

    enc = make_zip([("a.txt", b"alpha\n")], zipfile.ZIP_STORED)
    cd = find_cdir(enc, "a.txt")
    struct.pack_into("<H", enc, cd + 8, struct.unpack_from("<H", enc, cd + 8)[0] | 1)
    zips["fx_zip_encrypted"] = enc

    z64 = make_zip([("a.txt", b"alpha\n")], zipfile.ZIP_STORED)
    eocd = z64.rfind(b"PK\x05\x06")
    struct.pack_into("<HH", z64, eocd + 8, 0xFFFF, 0xFFFF)
    zips["fx_zip_zip64"] = z64

    # Packages for the installer.
    zips["fx_pkg_v1"] = make_zip([("manifest.toml", manifest("1.0.0")), ("app.elf", big_elf),
                                  ("icon.png", icon), ("assets/", b""), ("assets/readme.txt", readme)])
    zips["fx_pkg_v2"] = make_zip([("manifest.toml", manifest("1.1.0", icon=False)),
                                  ("app.elf", b"\x7fELF version two" * 64), ("new.txt", b"new file\n")])
    zips["fx_pkg_v0"] = make_zip([("manifest.toml", manifest("0.9.0", icon=False)), ("app.elf", b"old")])
    zips["fx_pkg_noentry"] = make_zip([("manifest.toml", manifest("1.0.0", entry="main.py", icon=False)),
                                       ("app.elf", b"x")])
    zips["fx_pkg_nomanifest"] = make_zip([("app.elf", b"x")])
    zips["fx_pkg_badapi"] = make_zip([("manifest.toml", manifest("1.0.0", api=2, icon=False)), ("app.elf", b"x")])
    zips["fx_pkg_other"] = make_zip([("manifest.toml", manifest("2.0.0", icon=False)
                                      .replace(b"com.example.hello", b"com.example.other")
                                      .replace(b'runtime = "native"', b'runtime = "micropython"')
                                      .replace(b'"app.elf"', b'"main.py"')),
                                     ("main.py", b"import t5\n")])

    for name, data in zips.items():
        out.append(c_array(name, bytes(data)))
        out.append("")
    out.append(f"#define FX_BIG_ELF_SIZE {len(big_elf)}u")
    out.append(f"#define FX_BIG_ELF_CRC 0x{zlib.crc32(big_elf):08x}u")
    out.append(f"#define FX_README_SIZE {len(readme)}u")
    out.append("")
    with open(OUT, "w") as f:
        f.write("\n".join(out))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
