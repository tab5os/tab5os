"""Freeze an SDK-built app ELF as a C array for test_app.c.
Usage: gen_app_elf_fixture.py test/apps/build/hello.elf > test/host/fixtures/app_elf_fixture.h"""
import sys

data = open(sys.argv[1], "rb").read()
print("/* Generated by gen_app_elf_fixture.py from the SDK template app (hello.elf). */")
print("#pragma once")
print("#include <stdint.h>")
print(f"static const uint8_t app_elf_fixture[{len(data)}] = {{")
for i in range(0, len(data), 16):
    print("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
print("};")
