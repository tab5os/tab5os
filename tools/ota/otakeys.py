#!/usr/bin/env python3
"""Turn the trusted update keys (firmware/ota_keys/*.pem, ECDSA P-256 public
keys) into a C table for t5_ota (plan 9.1).

usage: otakeys.py KEY_DIR OUT.c

Stdlib only: the PEM is decoded here, no openssl needed at build time.
A private key in KEY_DIR is an error: only public halves belong in the tree.
"""
import base64
import os
import re
import sys

from sign import key_id

P256_SPKI_PREFIX = bytes.fromhex("3059301306072a8648ce3d020106082a8648ce3d030107034200")


def load(path):
    text = open(path).read()
    if "PRIVATE KEY" in text:
        sys.exit(f"{path}: a private key; put only public keys in the firmware (openssl pkey -in k.pem -pubout)")
    m = re.search(r"-----BEGIN PUBLIC KEY-----(.*?)-----END PUBLIC KEY-----", text, re.S)
    if not m:
        sys.exit(f"{path}: no PUBLIC KEY block")
    der = base64.b64decode("".join(m.group(1).split()))
    if not der.startswith(P256_SPKI_PREFIX) or len(der) != len(P256_SPKI_PREFIX) + 65:
        sys.exit(f"{path}: not an uncompressed ECDSA P-256 public key")
    return key_id(der), der[-65:]


def main():
    key_dir, out = sys.argv[1], sys.argv[2]
    keys = []
    if os.path.isdir(key_dir):
        for fn in sorted(os.listdir(key_dir)):
            if fn.endswith(".pem"):
                kid, point = load(os.path.join(key_dir, fn))
                keys.append((fn[:-4], kid, point))
    lines = ["/* Generated by tools/ota/otakeys.py from firmware/ota_keys. Do not edit. */",
             '#include "ota_keys.h"', ""]
    lines.append("const t5_ota_key_t t5_ota_keys[] = {")
    for name, kid, point in keys:
        lines.append("    { \"%s\", { %s },\n      { %s } }," % (
            name[:31], ", ".join("0x%02x" % b for b in kid), ", ".join("0x%02x" % b for b in point)))
    if not keys:
        lines.append("    { \"\", { 0 }, { 0 } },   /* none: only unsigned images t5_ota_source_t lets in install */")
    lines.append("};")
    lines.append("const int t5_ota_nkeys = %d;" % len(keys))
    text = "\n".join(lines) + "\n"
    old = open(out).read() if os.path.exists(out) else None
    if old != text:
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, "w") as f:
            f.write(text)


if __name__ == "__main__":
    main()
