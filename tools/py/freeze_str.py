#!/usr/bin/env python3
"""Freeze Python source into the firmware as MicroPython frozen strings.

usage: freeze_str.py OUT.c DIR[=PREFIX]...

Every .py under each DIR (except manifest.py) becomes an importable frozen
module named PREFIX/relative/path.py. The modules stay source: the VM
compiles them on import with the same compiler as app code, so freezing adds
no way to load bytecode or machine code (.mpy loading stays off, plan 8.2).
Output is deterministic; the file is only rewritten when it changes.
"""
import os
import sys


def collect(spec):
    d, _, prefix = spec.partition("=")
    out = []
    for root, dirs, files in os.walk(d):
        dirs.sort()
        for f in sorted(files):
            if not f.endswith(".py") or f == "manifest.py":
                continue
            path = os.path.join(root, f)
            rel = os.path.relpath(path, d).replace(os.sep, "/")
            name = (prefix + "/" + rel) if prefix else rel
            with open(path, "rb") as fh:
                out.append((name, fh.read()))
    return out


def c_bytes(data):
    rows = []
    for i in range(0, len(data), 24):
        rows.append("    " + ", ".join("0x%02x" % b for b in data[i : i + 24]) + ",")
    return "\n".join(rows)


def main(argv):
    if len(argv) < 3:
        sys.exit(__doc__)
    mods = []
    for spec in argv[2:]:
        mods += collect(spec)
    names = [m[0] for m in mods]
    if len(set(names)) != len(names):
        sys.exit("freeze_str: duplicate module names")
    lines = ["/* Generated by tools/py/freeze_str.py. Do not edit. */", "#include <stdint.h>", ""]
    lines.append("const char mp_frozen_names[] = {")
    for n in names:
        lines.append(c_bytes(n.encode() + b"\0"))
    lines.append("    0x00,\n};")
    lines.append("const uint32_t mp_frozen_str_sizes[] = { " + ", ".join(str(len(m[1])) for m in mods) + ", 0 };")
    lines.append("const char mp_frozen_str_content[] = {")
    for _, data in mods:
        lines.append(c_bytes(data + b"\0"))
    lines.append("};")
    text = "\n".join(lines) + "\n"
    out = argv[1]
    if os.path.exists(out) and open(out).read() == text:
        return
    os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
    with open(out, "w") as fh:
        fh.write(text)
    print("freeze_str: %d modules, %d bytes" % (len(mods), sum(len(m[1]) for m in mods)))


if __name__ == "__main__":
    main(sys.argv)
